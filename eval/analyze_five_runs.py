# Plan: docs/test_plan.md, Nov 25 note. Descriptive only, no hypothesis test. Reads eval/five_runs_results.jsonl
# (finished runs only; failed attempts are counted separately) and writes eval/five_runs_report.md.
#   python -m eval.analyze_five_runs
import json
import statistics
import time
from pathlib import Path

from eval.five_runs import RESULTS, ROUNDS, VERSIONS, companies

REPORT = Path("eval/five_runs_report.md")
TOKENS = [("prompt_tokens", "Prompt tokens"), ("output_tokens", "Output tokens"),
          ("thinking_tokens", "Thinking tokens"), ("model_calls", "Model calls")]


def load():
    runs, failed = [], 0
    with open(RESULTS, encoding="utf-8") as f:
        for line in f:
            if line.strip():
                r = json.loads(line)
                if r.get("error"):
                    failed += 1
                else:
                    runs.append(r)
    return runs, failed


def pct(values, q):
    """Nearest-rank percentile (q in 0..100) of a non-empty list."""
    s = sorted(values)
    return s[max(0, min(len(s) - 1, round(q / 100 * (len(s) - 1))))]


def fmt(x):
    return f"{x:,.0f}" if isinstance(x, (int, float)) else "n/a"


def letter(direction):
    return {"increase": "I", "decrease": "D"}.get(direction, "-")


def main():
    runs, failed = load()
    rows = companies()
    tickers = [r["ticker"] for r in rows]
    truth = {r["ticker"]: r["truth"] for r in rows}
    by = {(t, v): sorted([r for r in runs if r["ticker"] == t and r["prompt"] == v], key=lambda r: r["ts"])[:ROUNDS]
          for t in tickers for v in VERSIONS}
    out = ["# Five runs per company per version (set B, 20 companies)", "",
           f"Generated by `eval/analyze_five_runs.py` on {time.strftime('%Y-%m-%d %H:%M')}. Plan: `docs/test_plan.md`, "
           "Nov 25 note. Descriptive only. Backtest mode (the target year is hidden). A missing answer counts as wrong.",
           "", f"Finished runs: {sum(len(x) for x in by.values())} of {len(tickers) * len(VERSIONS) * ROUNDS}. "
           f"Failed attempts that were retried (outages, quota stops): {failed}.", ""]
    short = [f"{t} {v}: {len(by[(t, v)])}" for t in tickers for v in VERSIONS if len(by[(t, v)]) < ROUNDS]
    if short:
        out += ["Fewer than five finished runs: " + ", ".join(short) + ".", ""]

    out += ["## 1. Stability: how many of the runs agree on the direction", "",
            "| Version | 5 of 5 | 4 of 5 | 3 of 5 | Fewer than 5 runs | All five agree |", "|---|---|---|---|---|---|"]
    for v in VERSIONS:
        counts = {5: 0, 4: 0, 3: 0}
        incomplete = 0
        for t in tickers:
            dirs = [r["direction"] for r in by[(t, v)]]
            if len(dirs) < ROUNDS:
                incomplete += 1
                continue
            counts[max(dirs.count(d) for d in set(dirs))] += 1
        complete = len(tickers) - incomplete
        share = f"{counts[5]} of {complete} ({counts[5] / complete:.0%})" if complete else "n/a"
        out.append(f"| {v} | {counts[5]} | {counts[4]} | {counts[3]} | {incomplete} | {share} |")
    out += ["", "A missing answer is its own value here: five runs with one missing answer agree 4 of 5 at most.", ""]

    out += ["## 2. Accuracy, correct out of 20", "",
            "| Version | " + " | ".join(f"Round {i}" for i in range(1, ROUNDS + 1)) + " | Lowest | Highest | Majority of five |",
            "|---|" + "---|" * (ROUNDS + 3)]
    for v in VERSIONS:
        per_round = []
        for i in range(ROUNDS):
            got = [by[(t, v)][i] for t in tickers if len(by[(t, v)]) > i]
            per_round.append((sum(bool(r["correct"]) for r in got), len(got)))
        cells = [f"{c}" + (f" of {n}" if n != len(tickers) else "") for c, n in per_round]
        full = [c for c, n in per_round if n == len(tickers)]
        majority = 0
        for t in tickers:
            dirs = [r["direction"] for r in by[(t, v)]]
            top = max(set(dirs), key=dirs.count) if dirs else None
            if top is not None and dirs.count(top) * 2 > len(dirs) and top == truth[t]:
                majority += 1
        out.append(f"| {v} | " + " | ".join(cells) + f" | {min(full) if full else 'n/a'} | "
                   f"{max(full) if full else 'n/a'} | {majority} |")
    out += ["", "Round i is each company's i-th finished run. Majority of five: the direction more than half of the "
            "finished runs give; no majority counts as wrong.", ""]

    out += ["## 3. Cost per run (tokens billed, every model call of the run included)", "",
            "| Version | Measure | Median | 10th pct | 90th pct | Total |", "|---|---|---|---|---|---|"]
    for v in VERSIONS:
        mine = [r for t in tickers for r in by[(t, v)]]
        measures = [(label, [((r.get("usage") or {}).get("billed") or {}).get(key) for r in mine]) for key, label in TOKENS]
        measures.append(("Seconds", [r.get("seconds") for r in mine]))
        for label, values in measures:
            values = [x for x in values if isinstance(x, (int, float))]
            if values:
                out.append(f"| {v} | {label} | {fmt(statistics.median(values))} | {fmt(pct(values, 10))} | "
                           f"{fmt(pct(values, 90))} | {fmt(sum(values)) if label != 'Seconds' else ''} |")
            else:
                out.append(f"| {v} | {label} | n/a | n/a | n/a | |")
    out += ["", "## 4. Every run, by company", "",
            "Directions in run order: I increase, D decrease, - no answer.", "",
            "| Company | Truth | " + " | ".join(VERSIONS) + " |", "|---|---|" + "---|" * len(VERSIONS)]
    for t in tickers:
        out.append(f"| {t} | {letter(truth[t])} | " +
                   " | ".join("".join(letter(r["direction"]) for r in by[(t, v)]) or "(none)" for v in VERSIONS) + " |")
    REPORT.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"Wrote {REPORT}.")


if __name__ == "__main__":
    main()
