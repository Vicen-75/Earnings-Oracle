# --- Data helpers -----------------------------------------------------------------------------------------------
@st.cache_data(ttl=3600, show_spinner=False)
def load_company(ticker):
    """EDGAR checks before any model call (cached for an hour)."""
    cik, name = ticker_to_cik(ticker)
    if cik is None:
        return {"error": f"Ticker {ticker} was not found on EDGAR."}
    filings = list_10ks(cik, how_many=2)
    if not filings:
        return {"error": f"{name} does not file 10-K reports (it may be a foreign company that files a 20-F), "
                         "so there is nothing for the model to read. Answer: no data found."}
    return {"name": name, "cik": cik, "filings": filings, "ratios": compute_general_ratios(cik)}


@st.cache_resource
def analysis_store():
    """Shared across visitors: {ticker: (timestamp, result)}. Saves the free tier when the class clicks the same example."""
    return {}


def cached_analysis(ticker):
    hit = analysis_store().get(ticker)
    if hit and time.time() - hit[0] < CACHE_HOURS * 3600:
        return hit
    return None


def parse_headline(answer):
    """Direction and probability from the model's text, for the headline only. Returns (direction, probability);
    either can be None. The full answer is always shown below, so a parse miss loses nothing."""
    text = answer or ""
    direction = re.search(r"\*\*(increase|decrease)\*\*", text, re.I) \
        or re.search(r"direction\W+(increase|decrease)", text, re.I) \
        or re.search(r"(?:will|to)\s+(?:\*\*)?(increase|decrease)\b", text, re.I)
    probability = re.search(r"probability\W*(?:of\W*)?(0?\.\d+|1(?:\.0+)?)\b", text, re.I)
    return (direction.group(1).lower() if direction else None,
            float(probability.group(1)) if probability else None)


def fmt(value, kind):
    if not isinstance(value, (int, float)):
        return "not reported"
    if kind == "margin":
        return f"{value:.1%}"
    if kind == "growth":
        return f"{value:+.1%}"
    if kind == "days":
        return f"{value:,.0f} days"
    return f"{value:,.2f}x"


# --- Display helpers --------------------------------------------------------------------------------------------
def describe_action(step):
    """The tool call in plain words, e.g. 'compute_ratios: revenue_growth, gross_margin' or 'get_mdna for CIK 0000018230'."""
    args = dict(step["args"])
    if step["tool"] == "compute_ratios":
        return f"compute_ratios: {', '.join(args.get('ratios', []))}"
    shown = ", ".join(f"{k} {v}" for k, v in args.items())
    return f"{step['tool']} for {shown}" if shown else step["tool"]


def show_step(i, step):
    """One ReAct step: thought, action, observation."""
    st.markdown(f"**Step {i}. {TOOL_LABELS.get(step['tool'], step['tool'])}**")
    observation = step.get("observation") or ("ok" if step["ok"] else "the tool reported an error")
    observation_line = f"{observation}" if step["ok"] else f":red[{observation}]"
    st.markdown(f"- *Thought:* {step['reason'] or '(none given)'}\n"
                f"- *Action:* `{describe_action(step)}`\n"
                f"- *Observation:* {observation_line}")
    if step.get("substeps"):                       # the locator agent's own thought / action / observation loop
        lines = []
        for j, sub in enumerate(step["substeps"], 1):
            args = ", ".join(f"{k} {v}" for k, v in sub["args"].items())
            lines.append(f"    {j}. **[FY {sub['filing']}]** *Thought:* {sub['reason'] or '(none)'}  \n"
                         f"       *Action:* `{sub['tool']} {args}`  \n"
                         f"       *Observation:* {sub['observation']}")
        st.markdown("- *Locator agent steps:*\n" + "\n".join(lines))


def show_conclusion(i, target, direction, probability, answer):
    st.markdown(f"**Step {i}. Conclusion**")
    if "no data found" in answer.lower()[:300]:
        st.markdown("- No data found: nothing usable to predict from.")
    elif direction:
        prob = f" with probability {probability:.2f}" if probability is not None else ""
        st.markdown(f"- Weighed the evidence: {target.lower()} will **{direction}**{prob}. Reasoning in the answer above.")
    else:
        st.markdown("- See the answer above (direction could not be read from the text).")


def target_name(out):
    card = out["results"].get("get_company_card")
    target = card.get("target", "") if isinstance(card, dict) else ""
    return target.capitalize() if target and not target.startswith("none") else "Operating income"


PREDICTION_SENTENCE = re.compile(r"(predict\w*|expect\w*|likely|will)\b.*\b(increase|decrease)", re.I)
LABEL_LINE = re.compile(r"^\W*(direction|probability)\b", re.I)


def answer_body(answer):
    """The answer without its opening direction/probability lines, which the headline already shows."""
    lines = answer.splitlines()
    i, dropped_sentence = 0, False
    while i < len(lines):
        line = lines[i].strip()
        if not line or LABEL_LINE.match(line):
            i += 1
        elif not dropped_sentence and len(line) < 400 and PREDICTION_SENTENCE.search(line):
            dropped_sentence = True
            i += 1
        else:
            break
    body = "\n".join(lines[i:]).strip()
    return body or answer


def show_ratios(result, playbook):
    ratios = result.get("compute_ratios")
    if not isinstance(ratios, dict):
        st.info("The model did not compute any ratios.")
        return
    if "error" in ratios:
        st.warning(f"Ratios not available: {ratios['error']}")
        return
    why = {r["ratio"]: r["why_here"] for r in (playbook or {}).get("recommended_ratios", [])}
    years = ratios["fiscal_years"]
    rows = []
    for name, by_year in ratios["values"].items():
        kind = ratios["kinds"][name]
        row = {"Ratio": name.replace("_", " "), **{f"FY ending {y}": fmt(by_year.get(y), kind) for y in reversed(years)}}
        row["Why the playbook suggests it"] = why.get(name, "the model's own addition")
        rows.append(row)
    st.table(pd.DataFrame(rows).set_index("Ratio"))         # st.table wraps long text, st.dataframe cuts it off
    if ratios.get("check_before_relying"):
        st.caption(f"Flagged for the model: {ratios['check_before_relying']}")
    if ratios.get("unknown_ratios"):
        st.caption(f"Asked for but not in the directory: {', '.join(ratios['unknown_ratios'])}")


def show_result(ticker, company, out, cached_at=None):
    answer = out["answer"]
    direction, probability = parse_headline(answer)
    if "no data found" in answer.lower()[:300]:
        st.warning("The model answered: no data found.")
    elif direction:
        arrow = "▲" if direction == "increase" else "▼"
        label = f"{arrow} {target_name(out)} will {direction}"
        st.subheader(label + (f" (probability {probability:.0%})" if probability is not None else ""))
    if cached_at:
        st.caption(f"Result from {time.strftime('%H:%M', time.localtime(cached_at))} (cached, no new model run).")

    playbook = out["results"].get("get_industry_playbook")
    left, right = st.columns([3, 2])
    with left:
        st.markdown("#### The model's answer")
        st.markdown(answer_body(answer))
    with right:
        if isinstance(playbook, dict) and "error" not in playbook:
            st.markdown(f"#### Industry playbook: {playbook['label']}")
            st.caption(playbook["what_drives_operating_income"])
        st.markdown("#### Ratios the model chose")
        st.caption("Computed from EDGAR XBRL data. These are the tool's numbers, not the model's retelling.")
        show_ratios(out["results"], playbook)

    with st.expander(f"How the model worked: {len(out['steps'])} tool calls, then a conclusion "
                     "(thought, action, observation)", expanded=False):
        for i, step in enumerate(out["steps"], 1):
            show_step(i, step)
        show_conclusion(len(out["steps"]) + 1, target_name(out), direction, probability, answer)
        u = out["usage"]
        st.caption(f"{u['model_calls']} model calls, {u['prompt_tokens']:,} tokens in, {u['output_tokens']:,} tokens out.")

    mdna = out["results"].get("locate_mdna") or out["results"].get("get_mdna")
    with st.expander("Filings and MD&A read", expanded=False):
        for f in company["filings"]:
            st.markdown(f"- 10-K for fiscal year ending {f['fiscal_year_end']} (filed {f['filed']}): "
                        f"[open on EDGAR]({f['url']})")
        if mdna is None:
            st.caption("The model decided not to read the MD&A.")
        elif "error" in mdna:
            st.caption(f"MD&A: {mdna['error']}. The answer rests on the ratios only.")
        else:
            st.caption("MD&A sections read: " + ", ".join(
                f"FY ending {f['fiscal_year_end']} ({f['chars']:,} characters"
                f"{', ' + f['how_found'] if f.get('how_found') else ''}{', truncated' if f.get('truncated') else ''})"
                for f in mdna["filings"]))

    standard = company["ratios"]
    if isinstance(standard, dict) and "error" not in standard:
        with st.expander("Standard ratio table (same for every company, for reference)", expanded=False):
            labels = {"revenue_billion_usd": ("Revenue (USD billions)", "number"),
                      "operating_income_billion_usd": ("Operating income (USD billions)", "number"),
                      "operating_margin": ("Operating margin", "margin"),
                      "revenue_growth": ("Revenue growth", "growth"),
                      "operating_income_growth": ("Operating income growth", "growth"),
                      "asset_turnover": ("Asset turnover", "multiple"),
                      "liabilities_to_equity": ("Liabilities / equity", "multiple")}
            current, prior = standard["fy_current"], standard["fy_prior"]
            table = pd.DataFrame(
                {f"FY ending {prior['fiscal_year_end']}": [fmt(prior[k], kind) if kind != "number" else
                                                           (f"{prior[k]:,.2f}" if isinstance(prior[k], (int, float)) else "not reported")
                                                           for k, (_, kind) in labels.items()],
                 f"FY ending {current['fiscal_year_end']}": [fmt(current[k], kind) if kind != "number" else
                                                             (f"{current[k]:,.2f}" if isinstance(current[k], (int, float)) else "not reported")
                                                             for k, (_, kind) in labels.items()]},
                index=[label for label, _ in labels.values()],
            )
            st.table(table)


# --- Input ------------------------------------------------------------------------------------------------------
def pick_example(t):
    st.session_state.ticker = t
    st.session_state.run_now = True


st.write("Try an example:")
cols = st.columns(len(EXAMPLES))
for col, (t, label) in zip(cols, EXAMPLES.items()):
    col.button(f"{t}: {label}", on_click=pick_example, args=(t,), width="stretch")

# A form, so pressing Enter in the box submits it like the Analyze button (a plain text box only saves the text).
with st.form("ticker_form", border=False):
    ticker_col, button_col = st.columns([4, 1], vertical_alignment="bottom")
    ticker_col.text_input("Or type a ticker", key="ticker", placeholder="e.g. CAT")
    if button_col.form_submit_button("Analyze", type="primary", width="stretch"):
        st.session_state.run_now = True

# --- Run --------------------------------------------------------------------------------------------------------
if st.session_state.pop("run_now", False):
    ticker = (st.session_state.get("ticker") or "").upper().strip()
    if not ticker:
        st.warning("Please enter a ticker.")
        st.stop()

    try:
        with st.spinner("Checking the company on EDGAR..."):
            company = load_company(ticker)
    except Exception:
        company = {"error": "EDGAR could not be reached right now. Please try again in a minute."}
    if "error" in company:
        st.error(company["error"])
        st.stop()

    st.header(company["name"])
    hit = cached_analysis(ticker)
    if hit:
        show_result(ticker, company, hit[1], cached_at=hit[0])
        st.stop()

    if st.session_state.requests_used >= MAX_REQUESTS_PER_SESSION:
        st.error("You have reached the limit of new analyses for this session. The examples above may still be cached.")
        st.stop()
    st.session_state.requests_used += 1

    from src.agent import investigate          # imported here so the page loads even if the model client fails

    live = st.empty()                          # live progress while the model works; cleared when it is done
    with live.container():
        with st.status("The model is investigating...", expanded=True) as status:
            counter = {"n": 0}

            def on_event(event):
                if event["type"] == "wait":
                    st.write(f"Model busy (free tier limit), waiting {event['seconds']} seconds...")
                else:
                    counter["n"] += 1
                    show_step(counter["n"], event)

            try:
                out = investigate(ticker, on_event=on_event, write_log=False)
            except Exception as error:
                status.update(label="The analysis failed", state="error")
                st.error(f"The model could not complete the analysis ({type(error).__name__}). "
                         "Please try again in a minute.")
                st.stop()
    live.empty()

    analysis_store()[ticker] = (time.time(), out)
    show_result(ticker, company, out)

st.caption(f"New analyses used: {st.session_state.requests_used} / {MAX_REQUESTS_PER_SESSION}")
