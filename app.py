def describe_action(step):
    """The tool call in plain words, e.g. 'compute_ratios: revenue_growth, gross_margin' or 'get_mdna for CIK 0000018230'."""
    args = dict(step["args"])
    if step["tool"] == "compute_ratios":
        return f"compute_ratios: {', '.join(args.get('ratios', []))}"
    shown = ", ".join(f"{k} {v}" for k, v in args.items())
    return f"{step['tool']} for {shown}" if shown else step["tool"]


# --- The trace: one step per model call, across the main agent and the MD&A locator ----------------------------
# Each step is one model turn: the thought(s) it wrote, the tool call(s) it asked for, and what each returned.
# The main agent's turns and the locator's turns are numbered in one sequence, in the order they happened, so the
# number of steps is the number of model calls (Nov 5: before, the locator's turns were folded under one step).
def _step_key(entry, agent):
    if agent == "main":
        return ("main", entry.get("model_call", id(entry)))
    return ("locator", entry.get("filing"), entry.get("call", id(entry)))


def _agent_label(entry, agent):
    return "Main agent" if agent == "main" else f"MD&A locator, 10-K for FY ending {entry.get('filing')}"


def _show_item(entry):
    """Thought, action, observation for one tool call inside a step."""
    if entry["tool"] == "stop":
        st.markdown(f"- *Observation:* {entry['observation']}")
        return
    if entry["tool"] in ("draft_answer", "empty_reply"):   # the model answered (or came back empty): no tool was called
        st.markdown(f"- {entry['observation']}")
        return
    ok = entry.get("ok", not str(entry.get("observation", "")).startswith(("Error", "Rejected")))
    observation = entry.get("observation") or ("ok" if ok else "the tool reported an error")
    st.markdown(f"- *Thought:* {entry.get('reason') or '(none given)'}\n"
                f"- *Action:* `{describe_action(entry)}`\n"
                f"- *Observation:* {observation if ok else ':red[' + observation + ']'}")


class TraceWriter:
    """Writes the trace step by step (live, as events arrive, or all at once for a cached result)."""
    def __init__(self):
        self.n, self.key = 0, None

    def add(self, entry, agent="main"):
        key = _step_key(entry, agent)
        if key != self.key:                                  # a new model call starts a new step
            self.n += 1
            self.key = key
            suffix = {"draft_answer": " · Draft answer", "empty_reply": " · Empty reply"}.get(entry["tool"], "")
            st.markdown(f"**Step {self.n} · {_agent_label(entry, agent)}{suffix}**")
        _show_item(entry)
        for sub in entry.get("substeps", []):                # the locator's own model calls, in order
            self.add(sub, agent="locator")

    def conclude(self, out, direction, probability):
        self.n += 1
        st.markdown(f"**Step {self.n} · Main agent · Conclusion**")
        answer = out["answer"]
        if "no data found" in answer.lower()[:300]:
            st.markdown("- No data found: nothing usable to predict from.")
        elif direction:
            prob = f" with probability {probability:.2f}" if probability is not None else ""
            st.markdown(f"- Weighed the evidence: {target_name(out).lower()} will **{direction}**{prob}. "
                        "The reasoning is in the answer below.")
        else:
            st.markdown("- See the answer below (the direction could not be read from the text).")
        u = out["usage"]
        st.caption(f"Main agent: {u['model_calls']} model calls, {u['prompt_tokens']:,} tokens in, "
                   f"{u['output_tokens']:,} tokens out. Prompt {out.get('prompt', '?')}.")


def trace_label(n):
    return f"How the model worked: {n} steps, one per model call (thought, action, observation)"


def show_cached_trace(out):
    direction, probability = parse_headline(out["answer"])
    box = st.status("How the model worked", state="complete", expanded=True)
    with box:
        writer = TraceWriter()
        for entry in out["steps"]:
            writer.add(entry)
        writer.conclude(out, direction, probability)
    box.update(label=trace_label(writer.n), state="complete", expanded=True)


def target_name(out):
    card = out["results"].get("get_company_card")
    target = card.get("target", "") if isinstance(card, dict) else ""
    return target.capitalize() if target and not target.startswith("none") else "Operating income"


PREDICTION_SENTENCE = re.compile(r"(predict\w*|expect\w*|likely|will)\b.*\b(increase|decrease)", re.I)
LABEL_LINE = re.compile(r"^\W*(direction|probability)\b", re.I)


def answer_body(answer):
    """The answer without its opening direction/probability lines, which the headline already shows."""
    lines = answer.splitlines()
    i, dropped_sentence = 0, False
    while i < len(lines):
        line = lines[i].strip()
        if not line or LABEL_LINE.match(line):
            i += 1
        elif not dropped_sentence and len(line) < 400 and PREDICTION_SENTENCE.search(line):
            dropped_sentence = True
            i += 1
        else:
            break
    body = "\n".join(lines[i:]).strip()
    return body or answer


def show_ratios(result, playbook):
    ratios = result.get("compute_ratios")
    if not isinstance(ratios, dict):
        st.info("The model did not compute any ratios.")
        return
    if "error" in ratios:
        st.warning(f"Ratios not available: {ratios['error']}")
        return
    why = {r["ratio"]: r["why_here"] for r in (playbook or {}).get("recommended_ratios", [])}
    years = ratios["fiscal_years"]
    rows = []
    for name, by_year in ratios["values"].items():
        kind = ratios["kinds"][name]
        row = {"Ratio": name.replace("_", " "), **{f"FY ending {y}": fmt(by_year.get(y), kind) for y in reversed(years)}}
        row["Why the playbook suggests it"] = why.get(name, "the model's own addition")
        rows.append(row)
    st.table(pd.DataFrame(rows).set_index("Ratio"))         # st.table wraps long text, st.dataframe cuts it off
    if ratios.get("check_before_relying"):
        st.caption(f"Flagged for the model: {ratios['check_before_relying']}")
    if ratios.get("unknown_ratios"):
        st.caption(f"Asked for but not in the directory: {', '.join(ratios['unknown_ratios'])}")


def show_failure(error):
    """Say why an analysis failed, in words a classmate can act on (Nov 6: the reason used to sit inside the collapsed
    trace box, and 'try again in a minute' was wrong when the daily quota was gone)."""
    kind = getattr(error, "kind", None)                 # src.key_pool.ModelBusy
    if kind == "daily_quota":
        st.error("The app has used up today's free model quota, so it cannot start new analyses until the quota "
                 "resets (midnight Pacific time). Analyses run earlier today are still available: try the examples "
                 "above.")
    elif kind == "rate_limit":
        st.error("The model is getting too many requests right now (free-tier limit per minute). "
                 "Please try again in a minute or two.")
    elif kind == "overloaded":
        st.error("Google's model service is overloaded right now. Please try again in a few minutes.")
    else:
        st.error(f"The model could not complete the analysis ({type(error).__name__}). Please try again in a minute.")


def show_baseline(company, direction):
    """Issue #46 (Nov 6): the momentum baseline next to the model's verdict, as the proposal promised.
    A fixed rule on two numbers, no model call: next year moves the same way as last year."""
    base = company.get("baseline")               # missing in results cached before this change
    if not base:
        return
    if not base.get("direction"):
        st.caption(f"Baseline (no model): not available, {base.get('reason', 'unknown reason')}.")
        return
    arrow = "▲" if base["direction"] == "increase" else "▼"
    metric = {"operating_income": "operating income", "pretax_income": "pre-tax income"}.get(base.get("target"),
                                                                                              "the target metric")
    verb = "rose" if base["direction"] == "increase" else "did not rise"
    older, newer = sorted(base["years"])
    agree = ""
    if direction:
        agree = " The model **agrees**." if direction == base["direction"] else \
                " The model **disagrees** with the trend."
    st.markdown(f"**Baseline (no model): {arrow} {base['direction']}.** Momentum rule: next year moves the way last year "
                f"did. {metric.capitalize()} {verb} from ${base['previous'] / 1e9:,.2f}B (FY ending {older}) to "
                f"${base['latest'] / 1e9:,.2f}B (FY ending {newer}).{agree}")


def show_result(ticker, company, out, cached_at=None):
    answer = out["answer"]
    direction, probability = parse_headline(answer)
    if "no data found" in answer.lower()[:300]:
        st.warning("The model answered: no data found.")
    elif direction:
        arrow = "▲" if direction == "increase" else "▼"
        label = f"{arrow} {target_name(out)} will {direction}"
        st.subheader(label + (f" (probability {probability:.0%})" if probability is not None else ""))
        show_baseline(company, direction)
    if cached_at:
        st.caption(f"Result from {time.strftime('%H:%M', time.localtime(cached_at))} (cached, no new model run).")

    playbook = out["results"].get("get_industry_playbook")
    left, right = st.columns([3, 2])
    with left:
        st.markdown("#### The model's answer")
        st.markdown(answer_body(answer))
    with right:
        if isinstance(playbook, dict) and "error" not in playbook:
            st.markdown(f"#### Industry playbook: {playbook['label']}")
            st.caption(playbook["what_drives_operating_income"])
        st.markdown("#### Ratios the model chose")
        st.caption("Computed from EDGAR XBRL data. These are the tool's numbers, not the model's retelling.")
        show_ratios(out["results"], playbook)

    mdna = out["results"].get("locate_mdna") or out["results"].get("get_mdna")
    with st.expander("Filings and MD&A read", expanded=False):
        for f in company["filings"]:
            st.markdown(f"- 10-K for fiscal year ending {f['fiscal_year_end']} (filed {f['filed']}): "
                        f"[open on EDGAR]({f['url']})")
        if mdna is None:
            st.caption("The model decided not to read the MD&A.")
        elif "error" in mdna:
            st.caption(f"MD&A: {mdna['error']}. The answer rests on the ratios only.")
        else:
            st.caption("MD&A sections read: " + ", ".join(
                f"FY ending {f['fiscal_year_end']} ({f['chars']:,} characters"
                f"{', ' + f['how_found'] if f.get('how_found') else ''}{', truncated' if f.get('truncated') else ''})"
                for f in mdna["filings"]))

    standard = company["ratios"]
    if isinstance(standard, dict) and "error" not in standard:
        with st.expander("Standard ratio table (same for every company, for reference)", expanded=False):
            labels = {"revenue_billion_usd": ("Revenue (USD billions)", "number"),
                      "operating_income_billion_usd": ("Operating income (USD billions)", "number"),
                      "operating_margin": ("Operating margin", "margin"),
                      "revenue_growth": ("Revenue growth", "growth"),
                      "operating_income_growth": ("Operating income growth", "growth"),
                      "asset_turnover": ("Asset turnover", "multiple"),
                      "liabilities_to_equity": ("Liabilities / equity", "multiple")}
            current, prior = standard["fy_current"], standard["fy_prior"]
            table = pd.DataFrame(
                {f"FY ending {prior['fiscal_year_end']}": [fmt(prior[k], kind) if kind != "number" else
                                                           (f"{prior[k]:,.2f}" if isinstance(prior[k], (int, float)) else "not reported")
                                                           for k, (_, kind) in labels.items()],
                 f"FY ending {current['fiscal_year_end']}": [fmt(current[k], kind) if kind != "number" else
                                                             (f"{current[k]:,.2f}" if isinstance(current[k], (int, float)) else "not reported")
                                                             for k, (_, kind) in labels.items()]},
                index=[label for label, _ in labels.values()],
            )
            st.table(table)


