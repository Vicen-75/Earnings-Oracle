def verdict_badge(correct):
    """Coloured verdict for markdown: status labels, the finished-test line."""
    return ":green[**✔ correct**]" if correct else ":red[**✘ wrong**]"


def draw_results(board, table_box, rows, store, base, running=None):
    """Scoreboard and results table. running = ticker being tested right now (its row is highlighted)."""
    from src.backtest import is_correct
    done = [r for r in rows if r["ticker"] in store]
    n = len(done)
    model_ok = sum(store[r["ticker"]]["correct"] for r in done)
    mom_ok = sum(is_correct(base[r["ticker"]]["momentum"]["direction"], r["truth"]) for r in done)
    inc_ok = sum(is_correct("increase", r["truth"]) for r in done)
    mom_all = sum(is_correct(base[r["ticker"]]["momentum"]["direction"], r["truth"]) for r in rows)
    inc_all = sum(is_correct("increase", r["truth"]) for r in rows)
    with board.container():
        c1, c2, c3 = st.columns(3)
        c1.metric("Model", f"{model_ok} of {n}" if n else "not run yet", help="Correct directions among the tests run")
        c2.metric("Momentum baseline", f"{mom_ok} of {n}" if n else "-", help="On the same companies as the model")
        c3.metric("Always increase", f"{inc_ok} of {n}" if n else "-", help="On the same companies as the model")
        st.caption(f"On all {len(rows)} companies: momentum {mom_all} of {len(rows)}, always increase {inc_all} of "
                   f"{len(rows)}. With 20 companies, one company is 5 points: a one-company difference is not "
                   "evidence.")

    mark = lambda ok: "✔" if ok else "✘"                       # noqa: E731
    table = []
    for r in rows:
        t = r["ticker"]
        res = store.get(t)
        mom = base[t]["momentum"]["direction"]
        model = "⏳ running…" if t == running else ((res["direction"] or "no answer") if res else "")
        table.append({
            "Ticker": t, "Company": r["name"].title(), "Industry": r["industry"],
            "Truth": "▲ increase" if r["truth"] == "increase" else "▼ decrease",
            "Model": model,
            "Probability": f"{res['probability']:.2f}" if res and res["probability"] is not None and t != running else "",
            "Model ✔": mark(res["correct"]) if res and t != running else "",
            "Momentum": mom or "n/a", "Momentum ✔": mark(is_correct(mom, r["truth"])),
            "Always ▲ ✔": mark(r["truth"] == "increase"),
        })
    df = pd.DataFrame(table)

    def verdict_style(value):
        if value == "✔":
            return f"background-color: {GREEN_BG}; color: {GREEN_FG}; font-weight: 600; text-align: center"
        if value == "✘":
            return f"background-color: {RED_BG}; color: {RED_FG}; font-weight: 600; text-align: center"
        return ""

    def running_style(row):
        return [f"background-color: {AMBER_BG}" if row["Ticker"] == running else "" for _ in row]

    styled = (df.style.apply(running_style, axis=1)
              .map(verdict_style, subset=["Model ✔", "Momentum ✔", "Always ▲ ✔"]))
    table_box.dataframe(styled, hide_index=True, width="stretch", height=38 + 35 * len(df))


def run_queue(queue, store, anonymize=False, redraw=None):
    """Run the queued tests one by one. Each result is stored as soon as it finishes, so a stall or an interruption
    only loses the test in progress. Clicking other buttons while this runs restarts the page and stops the queue."""
    from src.agent import APP_LOG_PATH, investigate
    from src.backtest import run_test
    from src.run_limiter import waiting_line
    st.warning("Tests are running. Keep this tab open and avoid clicking other controls until they finish.")
    progress = st.progress(0.0, text=f"0 of {len(queue)} done")
    for i, row in enumerate(queue):
        if redraw:
            redraw(row["ticker"])                   # highlight the company being tested
        with st.status(f"{row['ticker']}: the model is investigating (FY2025 hidden)...", expanded=True) as status:
            writer = TraceWriter()

            def on_event(event):
                if event["type"] == "wait":
                    st.caption(f"Model busy (free tier limit), waiting {event['seconds']} seconds...")
                else:
                    _ = writer.add(event)

            def on_wait(position, running, ticker=row["ticker"]):
                status.update(label=f"{ticker}: waiting for a free slot (#{position} in line, {running} running)...")
            try:
                with waiting_line.slot(on_wait):      # tests share the waiting line with visitors (Nov 6)
                    status.update(label=f"{row['ticker']}: the model is investigating (FY2025 hidden)...")
                    res = run_test(row, investigate, parse_headline, on_event=on_event, log_path=APP_LOG_PATH,
                                   anonymize=anonymize)
                store[row["ticker"]] = res
                status.update(label=f"**{row['ticker']}**: model {res['direction'] or 'no answer'}, truth "
                                    f"{row['truth']} · {verdict_badge(res['correct'])}",
                              state="complete", expanded=False)
            except Exception as error:
                status.update(label=f"**{row['ticker']}**: :orange[failed ({type(error).__name__}); try it again later]",
                              state="error", expanded=False)
        progress.progress((i + 1) / len(queue), text=f"{i + 1} of {len(queue)} done")
        if redraw:
            redraw(None)                            # the finished row fills in right away


def analyze_tab():
    st.write("Try an example:")
    cols = st.columns(len(EXAMPLES))
    for col, (t, label) in zip(cols, EXAMPLES.items()):
        col.button(f"{t}: {label}", on_click=pick_example, args=(t,), width="stretch")

    # A form, so pressing Enter in the box submits it like the Analyze button (a plain text box only saves the text).
    with st.form("ticker_form", border=False):
        ticker_col, button_col = st.columns([4, 1], vertical_alignment="bottom")
        ticker_col.text_input("Or type a ticker", key="ticker", placeholder="e.g. CAT")
        if button_col.form_submit_button("Analyze", type="primary", width="stretch"):
            st.session_state.run_now = True

    # --- Run --------------------------------------------------------------------------------------------------------
    if st.session_state.pop("run_now", False):
        ticker = (st.session_state.get("ticker") or "").upper().strip()
        if not ticker:
            st.warning("Please enter a ticker.")
            st.stop()

        try:
            with st.spinner("Checking the company on EDGAR..."):
                company = load_company(ticker)
        except Exception:
            company = {"error": "EDGAR could not be reached right now. Please try again in a minute."}
        if "error" in company:
            st.error(company["error"])
            st.stop()

        st.header(company["name"])
        hit = cached_analysis(ticker)
        if hit:
            show_cached_trace(hit[1])                  # same place and look as a live run: trace on top, open
            show_result(ticker, company, hit[1], cached_at=hit[0])
            st.stop()

        if st.session_state.requests_used >= MAX_REQUESTS_PER_SESSION:
            st.error("You have reached the limit of new analyses for this session. The examples above may still be cached.")
            st.stop()
        st.session_state.requests_used += 1

        from src.agent import investigate, APP_LOG_PATH   # imported here so the page loads even if the model client fails
        from src.run_limiter import waiting_line

        # Waiting line (Nov 6): at most a few analyses run at once across all visitors, so a class of 35 does not burst
        # past the free-tier limits of every key. Everyone else waits here, first come, first served.
        line_box = st.empty()

        def on_wait(position, running):
            line_box.info(f"The app is busy ({running} analyses running). You are **#{position}** in line; "
                          "your analysis starts automatically. Keep this tab open.", icon="⏳")

        try:
            with waiting_line.slot(on_wait):
                line_box.empty()

                # The trace is written live into this box and stays here, open, as the record of the run
                # (Nov 5: it used to be cleared and redrawn at the bottom of the page, which was disorienting).
                with st.status("The model is investigating...", expanded=True) as status:
                    writer = TraceWriter()

                    def on_event(event):
                        if event["type"] == "wait":
                            st.caption(f"Model busy (free tier limit), waiting {event['seconds']} seconds...")
                        else:
                            _ = writer.add(event)

                    try:
                        out = investigate(ticker, on_event=on_event, log_path=APP_LOG_PATH)  # git-ignored record
                    except Exception as error:
                        failure = error
                    else:
                        failure = None
                    if failure is not None:
                        status.update(label="The analysis failed", state="error", expanded=False)
                    else:
                        writer.conclude(out, *parse_headline(out["answer"]))
                if failure is not None:
                    show_failure(failure)                      # below the box, where people see it (Nov 6)
                    st.stop()
                status.update(label=trace_label(writer.n), state="complete", expanded=True)
        except TimeoutError:
            line_box.empty()
            st.error("The app has been busy for a long time. Please try again in a few minutes.")
            st.stop()
        analysis_store()[ticker] = (time.time(), out)
        show_result(ticker, company, out)

    st.caption(f"New analyses used: {st.session_state.requests_used} / {MAX_REQUESTS_PER_SESSION} · {server_load()}")


def server_load():
    """One line on how busy the app is: analyses running and waiting, and how many API keys share the work."""
    try:
        from src.key_pool import pool
        from src.run_limiter import waiting_line
    except Exception:
        return "model client unavailable"
    line = waiting_line.status()
    return (f"Server: {line['running']} of {line['limit']} analysis slots in use, {line['waiting']} waiting, "
            f"{len(pool.keys)} API key(s)")


