import pandas as pd
import streamlit as st

from src.edgar import ticker_to_cik, list_10ks
from src.ratios import compute_general_ratios

MAX_REQUESTS_PER_SESSION = 10      # limit per visitor, so the class cannot use up our free tier

st.title("Earnings Oracle")
st.caption("Output is generated by a language model and may be wrong. It is not financial advice.")

if "requests_used" not in st.session_state:
    st.session_state.requests_used = 0


@st.cache_data(ttl=3600, show_spinner=False)
def load_company(ticker):
    """Everything we need from EDGAR for one ticker (cached for an hour)."""
    cik, name = ticker_to_cik(ticker)
    if cik is None:
        return {"error": f"Ticker {ticker} was not found on EDGAR."}
    filings = list_10ks(cik, how_many=2)
    if not filings:
        return {"error": f"{name} does not file 10-K reports (it may be a foreign company that files a 20-F)."}
    return {"name": name, "cik": cik, "filings": filings, "ratios": compute_general_ratios(cik)}


LABELS = {
    "revenue_billion_usd": ("Revenue (USD billions)", "number"),
    "operating_income_billion_usd": ("Operating income (USD billions)", "number"),
    "operating_margin": ("Operating margin", "percent"),
    "revenue_growth": ("Revenue growth vs previous year", "percent"),
    "operating_income_growth": ("Operating income growth vs previous year", "percent"),
    "asset_turnover": ("Asset turnover", "number"),
    "liabilities_to_equity": ("Liabilities / equity", "number"),
}


def show(value, kind):
    if not isinstance(value, (int, float)):
        return "not reported"
    return f"{value:.1%}" if kind == "percent" else f"{value:,.2f}"


ticker = st.text_input("Ticker (e.g. CAT)")

if st.button("Analyze"):
    if not ticker.strip():
        st.warning("Please enter a ticker.")
    elif st.session_state.requests_used >= MAX_REQUESTS_PER_SESSION:
        st.error("You have reached the limit of analyses for this session.")
    else:
        st.session_state.requests_used += 1
        try:
            with st.spinner("Reading the company's filings on EDGAR..."):
                company = load_company(ticker.upper().strip())
        except Exception:
            company = {"error": "EDGAR could not be reached right now. Please try again in a minute."}

        if "error" in company:
            st.error(company["error"])
        else:
            st.subheader(company["name"])
            st.write("10-K filings used:")
            for f in company["filings"]:
                st.markdown(f"- Fiscal year ending {f['fiscal_year_end']} (filed {f['filed']}): [open on EDGAR]({f['url']})")

            ratios = company["ratios"]
            if "error" in ratios:
                st.warning(f"Ratios not available: {ratios['error']}")
            else:
                current, prior = ratios["fy_current"], ratios["fy_prior"]
                table = pd.DataFrame(
                    {f"FY ending {prior['fiscal_year_end']}": [show(prior[k], kind) for k, (_, kind) in LABELS.items()],
                     f"FY ending {current['fiscal_year_end']}": [show(current[k], kind) for k, (_, kind) in LABELS.items()]},
                    index=[label for label, _ in LABELS.values()],
                )
                st.write("Key ratios, computed from the company's XBRL data on EDGAR:")
                st.table(table)

            st.info("Next step (in progress): the model reads the MD&A and predicts whether operating income "
                    "will increase or decrease next year, with the passages that drove the call.")

st.caption(f"Analyses used: {st.session_state.requests_used} / {MAX_REQUESTS_PER_SESSION}")
